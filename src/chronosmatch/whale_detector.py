from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

from chronosmatch.order import Order, OrderSide
from chronosmatch.trade import Trade


@dataclass(frozen=True, slots=True)
class WhaleOrder:
    """
    Representation of a detected Whale order execution.

    Attributes:
        order_id: Unique identifier of the incoming aggressive order.
        side: OrderSide (BUY or SELL) of the incoming order.
        levels_swept: Number of distinct price levels matched (>= 2).
        execution_prices: Sorted tuple of distinct execution prices swept.
        total_quantity: Total volume executed across all matched trades.
        trades: Tuple of Trade execution events generated by this order.
        timestamp_ns: Timestamp of the incoming order in nanoseconds.
        is_partial: True if the order was partially filled, False if fully filled.
    """
    order_id: int
    side: OrderSide
    levels_swept: int
    execution_prices: tuple[int, ...]
    total_quantity: int
    trades: tuple[Trade, ...]
    timestamp_ns: int
    is_partial: bool


def detect_whale(order: Order, trades: Sequence[Trade]) -> WhaleOrder | None:
    """
    Detect whether an incoming order qualifies as a Whale order.

    A Whale order is identified when execution occurs across at least 2 distinct
    trade price levels.

    Args:
        order: The incoming Order instance processed by the matching engine.
        trades: Sequence of Trade records returned by MatchingEngine.process_order().

    Returns:
        WhaleOrder instance if the order swept >= 2 price levels, else None.
    """
    if not isinstance(order, Order):
        raise TypeError(f"order must be an instance of Order, got {type(order).__name__}")

    if not trades:
        return None

    # Collect distinct price levels
    distinct_prices = {trade.price for trade in trades}
    levels_swept = len(distinct_prices)

    # Condition: Execution across at least 2 distinct price levels
    if levels_swept < 2:
        return None

    total_quantity = sum(trade.quantity for trade in trades)
    is_partial = total_quantity < order.quantity

    return WhaleOrder(
        order_id=order.order_id,
        side=order.side,
        levels_swept=levels_swept,
        execution_prices=tuple(sorted(distinct_prices)),
        total_quantity=total_quantity,
        trades=tuple(trades),
        timestamp_ns=order.timestamp_ns,
        is_partial=is_partial,
    )


class WhaleDetector:
    """Convenience class wrapper for whale order detection."""

    @staticmethod
    def detect(order: Order, trades: Sequence[Trade]) -> WhaleOrder | None:
        """Evaluate order and trades for whale execution."""
        return detect_whale(order, trades)